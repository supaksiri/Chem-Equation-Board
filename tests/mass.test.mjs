import test from 'node:test';
import assert from 'node:assert/strict';
import {U_TO_G,MASSES,massOf,average,isotopeMix,molecularMass,canAdd,isComplete,MOLECULES} from '../src/chemistry/mass.ts';
test('u to grams constant',()=>assert.ok(Math.abs(U_TO_G-1.66053906660e-24)<1e-32));
test('C12 isotopic reference',()=>assert.equal(MASSES['C-12'],12));
test('C13 has mass above 13 u',()=>assert.ok(MASSES['C-13']>13));
test('mass sample proportional to count',()=>assert.equal(massOf('C-12',3),36));
test('weighted average endpoints',()=>{assert.equal(average([10,20],[100,0]),10);assert.equal(average([10,20],[0,100]),20)});
test('weighted average midpoint',()=>assert.equal(average([10,20],[50,50]),15));
test('weighted average rejects bad percent',()=>assert.throws(()=>average([10,20],[20,20])));
test('weighted average rejects mismatched arrays',()=>assert.throws(()=>average([10,20],[100])));
test('chlorine isotope average increases with heavier share',()=>assert.ok(isotopeMix(70).mass>isotopeMix(20).mass));
test('chlorine isotope mixture sums 100',()=>assert.equal(isotopeMix(27).light+isotopeMix(27).heavy,100));
test('isotope mixture clamps out of range',()=>{assert.equal(isotopeMix(-4).heavy,0);assert.equal(isotopeMix(120).heavy,100)});
test('Mr H2O approx 18.015',()=>assert.ok(Math.abs(molecularMass('H2O')-18.015)<.00001));
test('Mr CO2 approx 44.009',()=>assert.ok(Math.abs(molecularMass('CO2')-44.009)<.00001));
test('Mr H2O2 > H2O',()=>assert.ok(molecularMass('H2O2')>molecularMass('H2O')));
test('guided molecules may not overfill',()=>{assert.equal(canAdd('H2O',{H:2},'H'),false);assert.equal(canAdd('H2O',{H:1},'H'),true)});
test('guided assembly checks exact composition',()=>{assert.equal(isComplete('H2O',{H:2,O:1}),true);assert.equal(isComplete('H2O',{H:2,O:2}),false)});
test('all molecule weights positive',()=>Object.keys(MOLECULES).forEach(k=>assert.ok(molecularMass(k)>0)));
