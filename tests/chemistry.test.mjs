import test from 'node:test';
import assert from 'node:assert/strict';
import {adjust,atomicDifference,describe,formatCharge,isSameIsotope,MISSIONS,validAtom} from '../src/chemistry/atom.ts';
const C12={p:6,n:6,e:6},C13={p:6,n:7,e:6};
test('C-12 exactly 12 u',()=>assert.equal(describe(C12).massU,12));
test('C-13 isotope mass differs from mass number',()=>{assert.equal(describe(C13).A,13);assert.ok(describe(C13).massU>13)});
test('adding neutron preserves element',()=>{const x=adjust(C12,'n',1);assert.equal(describe(x).symbol,'C');assert.equal(describe(x).isotope,'C-13')});
test('electron changes charge not elemental identity',()=>{const x=adjust(C12,'e',-1);assert.equal(describe(x).Z,6);assert.equal(describe(x).charge,1)});
test('proton changes elemental identity',()=>assert.equal(describe(adjust(C12,'p',1)).symbol,'N'));
test('minimum proton is 1',()=>assert.deepEqual(adjust({p:1,n:0,e:1},'p',-1),{p:1,n:0,e:1}));
test('maximum proton 20',()=>assert.deepEqual(adjust({p:20,n:20,e:20},'p',1),{p:20,n:20,e:20}));
test('no negative particles',()=>assert.equal(adjust(C12,'n',-99).n,0));
test('no more than 40 electrons',()=>assert.equal(adjust(C12,'e',99).e,40));
test('unknown isotope should never fake mass',()=>assert.equal(describe({p:6,n:20,e:6}).massU,null));
test('isotope comparisons',()=>{assert.equal(isSameIsotope(C12,C13),false);assert.equal(atomicDifference(C12,C13).n,1)});
test('charge format',()=>{assert.equal(formatCharge(0),'เป็นกลาง');assert.equal(formatCharge(-2),'2−')});
test('mission C13 requires actual state',()=>{assert.equal(MISSIONS[0].check(C13,C12),true);assert.equal(MISSIONS[0].check(C12,C13),false)});
test('paired carbon mission',()=>assert.equal(MISSIONS[3].check(C12,C13),true));
test('difference 2 mission',()=>assert.equal(MISSIONS[4].check(C12,{p:6,n:8,e:6}),true));
test('valid atom only supported element range',()=>{assert.equal(validAtom(C12),true);assert.equal(validAtom({p:21,n:0,e:0}),false)});
